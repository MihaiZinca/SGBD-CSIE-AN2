CREATE OR REPLACE PROCEDURE ACTUALIZARE_SALARII_MICI(P_ID_DEPARTAMENT NUMBER,P_NR OUT NUMBER) IS
CURSOR C IS
    SELECT A.ID_ANGAJAT,A.NUME,A.PRENUME,A.SALARIUL,D.DENUMIRE_DEPARTAMENT
    FROM ANGAJATI A
    JOIN DEPARTAMENTE D ON A.ID_DEPARTAMENT=D.ID_DEPARTAMENT
    WHERE D.ID_DEPARTAMENT=P_ID_DEPARTAMENT;
R C%ROWTYPE;
BEGIN
    P_NR:=0;
    OPEN C;
    LOOP
        FETCH C INTO R;
        EXIT WHEN C%NOTFOUND;
        IF R.SALARIUL <5000 THEN
            
            UPDATE ANGAJATI
            SET SALARIUL=R.SALARIUL*1.10
            WHERE ID_ANGAJAT=R.ID_ANGAJAT;
            
            P_NR:=P_NR+1;
            DBMS_OUTPUT.PUT_LINE('Anajatului'||R.NUME||'din departaemtnul'||R.DENUMIRE_DEPARTAMENT);
        ELSE 
            DBMS_OUTPUT.PUT_LINE('NU NECESITA MODIFICARE');
        END IF;
    END LOOP;
    
    IF C%ROWCOUNT=0 THEN
        RAISE_APPLICATION_ERROR(-20000,'NU SUNT ANGAJATI IN ACEA CATEGORIE');
    END IF;
    CLOSE C;
    
END;
/

DECLARE 
    v_total number;
BEGIN
ACTUALIZARE_SALARII_MICI(50,v_total);
DBMS_OUTPUT.PUT_LINE('Numar total de angajati modificati: ' || v_total);
END;
/

