CREATE OR REPLACE FUNCTION NR_PROD_REDUSE_COMANDA(P_ID_COMANDA NUMBER)RETURN NUMBER IS
CURSOR C IS SELECT
    P.ID_PRODUS,
    P.DENUMIRE_PRODUS,
    P.PRET_LISTA
    FROM PRODUSE P
    JOIN RAND_COMENZI RC ON P.ID_PRODUS=RC.ID_PRODUS
    WHERE RC.ID_COMANDA=P_ID_COMANDA;
R C%ROWTYPE;
NR NUMBER:=0;
BEGIN 
    OPEN C;
    LOOP
        FETCH C INTO R;
        EXIT WHEN C%NOTFOUND;
        
        IF R.PRET_LISTA>200 THEN
            
            UPDATE PRODUSE 
            SET PRET_LISTA=R.PRET_LISTA*0.9
            WHERE ID_PRODUS=R.ID_PRODUS;
            
            NR:=NR+1;
             DBMS_OUTPUT.PUT_LINE('PRODUSUL '||' '||R.DENUMIRE_PRODUS||'  DIN COMANDA '||P_ID_COMANDA||' A FOST MODIFICAT');
        ELSE 
             DBMS_OUTPUT.PUT_LINE('NU NECESITA REDUCERE');
        END IF;
        
    END LOOP;
    CLOSE C;
    
    RETURN NR;
END;
/

