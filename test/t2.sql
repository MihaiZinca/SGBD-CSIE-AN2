--SA SE CONSTRUIASAC UN PACHET CARE CONTINE 
--O FUNCTIE CARE PRIMESTE CA PARAMETRUL ID UL UNUI PRODUS SI UN AN CALENDARISITIC(EX 2019)
--FUNCTIA VA RETURNA VALOAREA TOTALA PENTRU COMENZILE PRODUSULUI RESPECTIV IN ANUL RESPECTOV
-- O PROCEDURA CARE APELEAZA FUNCTIA DINTR UN CURSOR,PROCEDURA VA DECLANSA O EXCEPTIE DEFINITA DE UTILIZATOR
--EXCEPTIA SE VA DECLANSA DACA VAL COMENZILOR PENTRU ACEL AN <500.000
--SA SE APELEZE PROCEDURA DINTR UN BLOC ANONIMC, SA SE TRATEZE EXCEPTIA FARA A FOLOSI OTHERS


CREATE OR REPLACE PACKAGE MK IS
    FUNCTION TOTAL(P_ID_PRODUS NUMBER,P_AN NUMBER)RETURN NUMBER;
    PROCEDURE AFIS(P_AN NUMBER);
    
    NO_VAL EXCEPTION;
    PRAGMA EXCEPTION_INIT(NO_VAL,-20000);
END;
/

CREATE OR REPLACE PACKAGE BODY MK IS

     FUNCTION TOTAL(P_ID_PRODUS NUMBER,P_AN NUMBER)RETURN NUMBER IS
     V_TOT NUMBER;
     BEGIN
        SELECT SUM(R.PRET*R.CANTITATE)INTO V_TOT
        FROM COMENZI C
        JOIN RAND_COMENZI R ON C.ID_COMANDA=R.ID_COMANDA
        WHERE R.ID_PRODUS=P_ID_PRODUS
        AND EXTRACT(YEAR FROM C.DATA)=P_AN;
        
        RETURN NVL(V_TOT,0);
     END;
     
     PROCEDURE AFIS(P_AN NUMBER) IS
        CURSOR C IS SELECT
            ID_PRODUS,DENUMIRE_PRODUS,TOTAL(ID_PRODUS,P_AN) AS VAL
            FROM PRODUSE
            ORDER BY VAL DESC;
        
        R C%ROWTYPE;
        V_SUMA NUMBER DEFAULT 0;
     BEGIN
        IF NOT C%ISOPEN THEN
            OPEN C;
        END IF;
        LOOP
            FETCH C INTO R;
            EXIT WHEN C%NOTFOUND;
                DBMS_OUTPUT.PUT_LINE(R.ID_PRODUS||' '||R.VAL);
                V_SUMA:=V_SUMA+R.VAL;
        END LOOP;
        CLOSE C;
        
        IF V_SUMA<500000 THEN
            RAISE_APPLICATION_ERROR(-20000,'MAI MICA');
        END IF;
     END;
     
END;
/

DECLARE 
    TOT NUMBER;
BEGIN
    TOT:=MK.TOTAL(100,2020);
    DBMS_OUTPUT.PUT_LINE(TOT);
    
    MK.AFIS(2019);
    EXCEPTION
        WHEN MK.NO_VAL THEN
            DBMS_OUTPUT.PUT_LINE('EROARE'||SQLERRM);
END;
