--FOLOSIND UN CURSOR, SA SE AFISEZE DENUMIREA CATEGORIILOR DE PRODUSE SI VALOAREA TOTALA A COMENZILOR
--DIN PERSPECTIVELE CATEGORII. SE VOR AFISA DOAR CATEG CU VAL TOTALA A COMENZILOR >500000
--PT FIECARE CATEOGIRE SE VOR AFISA PRODUSELE DIN ACEA CATEGORIE SI VALOAREA TOALA COMENZILOR

DECLARE
    CURSOR C IS SELECT
    P.CATEGORIE,
    SUM(R.PRET * R.CANTITATE) VAL_T
    FROM PRODUSE P
    JOIN RAND_COMENZI R ON P.ID_PRODUS=R.ID_PRODUS
    GROUP BY P.CATEGORIE
    HAVING SUM(R.PRET* R.CANTITATE)>50000;
    
    CURSOR D(P_CATEG VARCHAR2) IS SELECT
    P.DENUMIRE_PRODUS,
    P.CATEGORIE,
    SUM(R.PRET * R.CANTITATE) VAL_T
    FROM PRODUSE P,RAND_COMENZI R
    WHERE P.ID_PRODUS=R.ID_PRODUS
    AND P.CATEGORIE=P_CATEG
    GROUP BY P.DENUMIRE_PRODUS,P.CATEGORIE;
BEGIN
    FOR R IN C LOOP
        DBMS_OUTPUT.PUT_LINE(R.CATEGORIE);
        FOR S IN D(R.CATEGORIE) LOOP
            DBMS_OUTPUT.PUT_LINE(S.DENUMIRE_PRODUS||':'||S.VAL_T);
        END LOOP;
    END LOOP;
END;
/

