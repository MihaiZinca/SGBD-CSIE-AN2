/*Să se construiască un pachet PL/SQL numit PKG_PERFORMANTA care să conțină:

O funcție (CALCULEAZA_VANZARI_DEPT) care primește ca parametru ID-ul unui departament și un an calendaristic. 
Funcția va returna valoarea totală a vânzărilor realizate de toți angajații din acel 
departament în anul respectiv (vânzările se calculează din RAND_COMENZI prin comenzile 
plasate în COMENZI de către angajații departamentului). Dacă departamentul nu are vânzări, funcția returnează 0.

O procedură (PROMOVEAZA_DEPARTAMENTE) care primește ca parametru un an calendaristic 
și un procent de mărire (ex. 10 pentru 10%). Procedura va folosi un cursor pentru a parcurge toate departamentele. Pentru fiecare departament, va apela funcția creată anterior.

Dacă valoarea totală a vânzărilor departamentului în acel an depășește 1.000.000, 
se va actualiza salariul maxim (SALARIU_MAX) în tabela FUNCTII cu procentul trimis ca parametru, 
însă doar pentru funcțiile deținute de angajații din acel departament.

Procedura va lansa o excepție definită de utilizator (FARA_VANZARI_ANUAL)
dacă mărirea se aplică unui an în care vânzările totale ale tuturor departamentelor cumulate sunt 0. 

Un bloc anonim care apelează procedura din pachet pentru anul 2021 și o mărire de 15%, 
tratând excepția personalizată fără a folosi OTHERS.
*/

CREATE OR REPLACE PACKAGE PKG_PERFORAMNTA IS
    FUNCTION CALCULEAZA_VANZARI_DEPT(P_ID_DEPARTAMENT NUMBER,P_AN NUMBER)RETURN NUMBER;
    PROCEDURE PROMOVEAZA_DEP(P_AN NUMBER,P_PROCENT NUMBER);
    FARA_VANZARI EXCEPTION;
    PRAGMA EXCEPTION_INIT(FARA_VANZARI,-20001);
END;
/

CREATE OR REPLACE PACKAGE BODY PKG_PERFORAMNTA IS
    FUNCTION CALCULEAZA_VANZARI_DEPT(P_ID_DEPARTAMENT NUMBER,P_AN NUMBER)RETURN NUMBER IS
    V_VAL NUMBER;
    BEGIN
        SELECT SUM(R.CANTITATE * R.PRET) INTO V_VAL
        FROM COMENZI C
        JOIN RAND_COMENZI R ON C.ID_COMANDA=R.ID_COMANDA
        JOIN ANGAJATI A ON C.ID_ANGAJAT=A.ID_ANGAJAT
        WHERE A.ID_DEPARTAMENT=P_ID_DEPARTAMENT 
        AND EXTRACT(YEAR FROM C.DATA)=P_AN;
        
        RETURN NVL(V_VAL,0);
    END;
    
    PROCEDURE PROMOVEAZA_DEP(P_AN NUMBER,P_PROCENT NUMBER) IS
        CURSOR C IS SELECT
            ID_DEPARTAMENT,DENUMIRE_DEPARTAMENT,CALCULEAZA_VANZARI_DEPT(ID_DEPARTAMENT,P_AN) VANZ
            FROM DEPARTAMENTE
            ORDER BY VANZ DESC;
        
        R C%ROWTYPE;
        V_SUMA NUMBER DEFAULT 0;
     BEGIN
        IF NOT C%ISOPEN THEN
            OPEN C;
        END IF;
        
        LOOP
            FETCH C INTO R;
            EXIT WHEN C%NOTFOUND;
            DBMS_OUTPUT.PUT_LINE(R.ID_DEPARTAMENT||' '||R.DENUMIRE_DEPARTAMENT||' '||R.VANZ);
            
            V_SUMA:=V_SUMA+R.VANZ;
            
            IF R.VANZ>1000000 THEN
             UPDATE FUNCTII
             SET SALARIU_MAX=SALARIU_MAX * (1+ P_PROCENT/100)
             WHERE ID_FUNCTIE IN(
             SELECT ID_FUNCTIE
             FROM ANGAJATI
             WHERE ID_DEPARTAMENT=R.ID_DEPARTAMENT);
            END IF;
        END LOOP;
        CLOSE C;

        IF V_SUMA=0 THEN
            RAISE_APPLICATION_ERROR(-20001,'FARA VANZARI');
        END IF;
    END;

END;
/

BEGIN 
    PKG_PERFORAMNTA.PROMOVEAZA_DEP(2015,15);
    EXCEPTION
        WHEN PKG_PERFORAMNTA.FARA_VANZARI THEN
            DBMS_OUTPUT.PUT_LINE('EROARE'||SQLERRM);
END;
/



