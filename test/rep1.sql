            DBMS_OUTPUT.PUT_LINE('Dept: ' || R1.ID_DEPARTAMENT || ' - ' || R1.DENUMIRE_DEPARTAMENT);
            IF NOT C2%ISOPEN THEN
                OPEN C2(R1.ID_DEPARTAMENT);
            END IF;
             
            LOOP
                FETCH C2 INTO R2;
                EXIT WHEN C2%NOTFOUND;
                DBMS_OUTPUT.PUT_LINE('   -> Angajat: ' || R2.NUME || ' | Salariu: ' || R2.SALARIUL);
            END LOOP;
            CLOSE C2;
        END LOOP;
     END;
     
