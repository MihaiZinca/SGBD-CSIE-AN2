-- SA SE CONSTRUIASACA O PROCEDURA CARE PRIMESTE O CATEG DE PRODUSE SI AFISEAZA DENUMIREA 
--FIECAURI PRODUS DIN ACEEA CATEGORIE PRECUM SI VALOAREA TOTALA A COMENZIILOR
--PT FIECARE PRODUS.DACA CATEGORIA NU EXISTA, SA SE RIDICE O EXCEPTIE

CREATE OR REPLACE PROCEDURE AFISARE_PROD(P_CATEGORIE VARCHAR2)IS
CURSOR C IS SELECT
    P.DENUMIRE_PRODUS,
    SUM(R.PRET * R.CANTITATE) AS VALOARE
    FROM PRODUSE P
    JOIN RAND_COMENZI R ON P.ID_PRODUS=R.ID_PRODUS
    WHERE CATEGORIE=P_CATEGORIE
    GROUP BY P.DENUMIRE_PRODUS;
    
    R C%ROWTYPE;
BEGIN
    IF NOT C%ISOPEN THEN
        OPEN C;
    END IF;
    LOOP
        FETCH C INTO R;
        EXIT WHEN C%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE(R.DENUMIRE_PRODUS||'->'||R.VALOARE);
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('NUMAR PROCEDURA PT CARE EXISTA COMENZI:'|| C%ROWCOUNT);
    
    IF C%ROWCOUNT=0 THEN
        RAISE_APPLICATION_ERROR(-20000,'NU SUNT PRODUSE IN ACEA CATEGORIE');
    END IF;
    CLOSE C;
END;
/

