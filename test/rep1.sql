--FOLOSIND O COLECTIE SA SE AFISEZE NUMELE ANG DIN DEP SA_REPT CU SALARILE INTRE 5000 SI 9000
--ANG VOR FI AFISATI IN ORDINEA DESC A VAL

DECLARE 
    TYPE R_ANG IS RECORD(
    NUME VARCHAR2(30),
    PRENUME VARCHAR2(30),
    SALARIUL NUMBER);
    
    TYPE T_ANG IS TABLE OF R_ANG INDEX BY PLS_INTEGER;
    V T_ANG;
    I PLS_INTEGER;
BEGIN
    SELECT NUME,PRENUME,SALARIUL
    BULK COLLECT INTO V
    FROM ANGAJATI
    WHERE ID_FUNCTIE='SA_REP'
    AND SALARIUL BETWEEN 5000 AND 9000
    ORDER BY SALARIUL DESC;
    
    I:=V.FIRST;
    WHILE I IS NOT NULL LOOP
         DBMS_OUTPUT.PUT_LINE(V(I).NUME || ' ' ||V(I).PRENUME||' ' ||'Salariul='||V(I).SALARIUL);
         I:=V.NEXT(I);
    END LOOP;
END;
/

--Folosind o colectie sa se afiseze denumirea produselor,valoara totala a comenzilor 
--precum si data ultimei 
--comenzi pt produsul respectiv
-- Se vor afisa produsele ordonate desc dupa data ultimei comenzi

DECLARE
    TYPE R_PR IS RECORD(
    DENUMIRE_PRODUS VARCHAR2(50),
    VALOARE_TOTALA NUMBER,
    DATA_ULTIMA_COMANDA TIMESTAMP);
    
    TYPE T_PR IS TABLE OF R_PR INDEX BY PLS_INTEGER;
    V T_PR;
    I PLS_INTEGER;
BEGIN
    SELECT P.DENUMIRE_PRODUS,
    SUM(RC.CANTITATE * RC.PRET) AS VALOARE_TOTALA,
    MAX(C.DATA) AS DATA_ULTIMA_COMANDA
    BULK COLLECT INTO V
    FROM PRODUSE P
    JOIN RAND_COMENZI RC ON P.ID_PRODUS=RC.ID_PRODUS
    JOIN COMENZI C ON RC.ID_COMANDA=C.ID_COMANDA
    GROUP BY P.DENUMIRE_PRODUS
    ORDER BY MAX(C.DATA) DESC;
    
    I:=V.FIRST;
    WHILE I IS NOT NULL LOOP
        DBMS_OUTPUT.PUT_LINE(V(I).denumire_produs || ' || Total=' || V(I).valoare_totala ||  ' || Ultima comanda=' || V(I).data_ultima_comanda);
        I:=V.NEXT(I);
    END LOOP;
    
END;
/

