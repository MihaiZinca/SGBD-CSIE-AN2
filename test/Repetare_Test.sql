    ORDER BY LIMITA_CREDIT DESC;
    
    R C%ROWTYPE;
BEGIN
    IF NOT C%ISOPEN THEN
        OPEN C;
    END IF;
    
    LOOP
        FETCH C INTO R;
        EXIT WHEN C%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE(C%ROWCOUNT||' '||R.NUME_CLIENT||' '||R.PRENUME_CLIENT||' '||R.LIMITA_CREDIT);
    END LOOP;
    CLOSE C;
        
END;
