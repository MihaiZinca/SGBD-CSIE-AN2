DECLARE 
    CURSOR C IS 
    SELECT NUME_CLIENT,PRENUME_CLIENT,LIMITA_CREDIT
    FROM CLIENTI
    WHERE ID_CLIENT IN(
    SELECT ID_CLIENT
    FROM COMENZI
    GROUP BY ID_CLIENT
