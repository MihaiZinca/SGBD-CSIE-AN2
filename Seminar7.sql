P.ID_PRODUS,
DENUMIRE_PRODUS,
PRET_LISTA
FROM PRODUSE P
JOIN RAND_COMENZI R ON P.ID_PRODUS=R.ID_PRODUS
GROUP BY P.ID_PRODUS,DENUMIRE_PRODUS,PRET_LISTA
HAVING COUNT(*)>=5;

DECLARE
    CURSOR C IS SELECT 
        P.ID_PRODUS,
        DENUMIRE_PRODUS,
        PRET_LISTA
        FROM PRODUSE P
        WHERE P.ID_PRODUS IN (SELECT R.ID_PRODUS 
                             FROM RAND_COMENZI R
                             GROUP BY R.ID_PRODUS
                             HAVING COUNT(R.ID_PRODUS)>=5) FOR UPDATE WAIT 10;
BEGIN
    FOR R IN C LOOP
        UPDATE PRODUSE
        SET PRET_LISTA=PRET_LISTA*1.05
