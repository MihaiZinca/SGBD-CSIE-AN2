--SA SE AFISEZE NUMELE SI PRENUMELE CLIENTULUI CARE A DAT CELE MAI MULTE COMENZI
--SE VOR AFISA COMENZILE PT RESPECTIVUL CLIENT 
-- ID_COMANDA, DATA, VAL TOATALA

DECLARE
    CURSOR C1 IS
        SELECT c.id_client, c.nume_client, c.prenume_client, COUNT(*) NR_COM
        FROM clienti c
        JOIN comenzi co ON c.id_client = co.id_client
        GROUP BY c.id_client, c.nume_client, c.prenume_client
        ORDER BY COUNT(*) DESC FETCH FIRST 1 ROW WITH TIES;

    CURSOR C2(P_ID NUMBER) IS
        SELECT c.id_comanda,
               c.data,
               SUM(r.pret * r.cantitate) AS val_tot
        FROM comenzi c
        JOIN rand_comenzi r ON c.id_comanda = r.id_comanda
        WHERE c.id_client = P_ID
        GROUP BY c.id_comanda, c.data;

BEGIN
    FOR R1 IN C1 LOOP
        DBMS_OUTPUT.PUT_LINE('Client: ' || R1.nume_client || ' ' || R1.prenume_client);
        FOR R2 IN C2(R1.id_client) LOOP
            DBMS_OUTPUT.PUT_LINE('Comanda: ' || R2.id_comanda ||' Data: ' || R2.data||' Total: ' || R2.val_tot);
        END LOOP;
    END LOOP;
END;
/

