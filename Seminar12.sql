--SA SE CONSTRUIASCA UN TRIGGER CARE SA PERMITA MAXIM 5 RANDURI IN TABELA REGIUNI

CREATE OR REPLACE TRIGGER VERIF_REG BEFORE INSERT ON REGIUNI
DECLARE
    NR NUMBER;
BEGIN
    SELECT COUNT(*) INTO NR FROM REGIUNI;
    IF NR>=5 THEN
        RAISE_APPLICATION_ERROR(-20000,'MAXIM 5 RANDURI IN TABELA');
    END IF;
END;
