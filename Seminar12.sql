--SA SE CONSTRUIASCA UN TRIGGER CARE NU PERMITE 
--ADAUGAREA DE COMENZI DUPA ORA 16:00
--MODIFICAREA DE COMENZI DUPA ORA 16:10
--STERGEREA DE COMENZI DUPA ORA 16:20

SET SERVEROUTPUT ON

--COMMIT SI ROLLBACK NU SE FOLOESC IN INTERIORUL UNUI TRIGGER
CREATE OR REPLACE TRIGGER VERIF_ORA BEFORE INSERT OR UPDATE OR DELETE ON COMENZI
BEGIN
    IF INSERTING AND TO_CHAR(SYSDATE,'HH24:MI')>='16:00' THEN
        RAISE_APPLICATION_ERROR(-20000,'NU SE POT ADAUGA COMENZI DUPA PRA 16');
         --DBMS_OUTPUT.PUT_LINE('S-A DECLANSAT TRIGGERUL INAINTEA UNEI OPERATII INSERT');
    ELSIF UPDATING AND TO_CHAR(SYSDATE,'HH24:MI')>='16:1O' THEN
          RAISE_APPLICATION_ERROR(-20000,'NU SE POT MODIFICA COMENZI DUPA PRA 16:10');
        --DBMS_OUTPUT.PUT_LINE('S-A DECLANSAT TRIGGERUL INAINTEA UNEI OPERATII UPDATE');
    ELSIF DELETING AND TO_CHAR(SYSDATE,'HH24:MI')>='16:20'THEN
        RAISE_APPLICATION_ERROR(-20000,'NU SE POT STERGE COMENZI DUPA PRA 16:20');
        --DBMS_OUTPUT.PUT_LINE('S-A DECLANSAT TRIGGERUL INAINTEA UNEI OPERATII DELETE');
    END IF;
END;
