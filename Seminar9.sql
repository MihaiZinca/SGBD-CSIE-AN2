CREATE OR REPLACE PROCEDURE MARESTE_PRET_PROD2(P_ID_PRODUS NUMBER, P_PROCENT NUMBER) IS
V_PRET_NOU NUMBER;
BEGIN
    UPDATE PRODUSE SET PRET_LISTA=PRET_LISTA*(100+P_PROCENT)/100 WHERE ID_PRODUS=P_ID_PRODUS
    RETURNING PRET_LISTA INTO V_PRET_NOU;
    
