--SA SE MODIFICE PROCEDURA ASTFEL INCAT SA SE AFISEZE SI PRRETUL NOU
CREATE OR REPLACE PROCEDURE MARESTE_PRET_PROD1(P_ID_PRODUS NUMBER, P_PROCENT NUMBER) IS
V_PRET_NOU NUMBER;
BEGIN
    UPDATE PRODUSE SET PRET_LISTA=PRET_LISTA*(100+P_PROCENT)/100 WHERE ID_PRODUS=P_ID_PRODUS;
    SELECT PRET_LISTA
        INTO V_PRET_NOU
        FROM PRODUSE
        WHERE ID_PRODUS = P_ID_PRODUS;
        DBMS_OUTPUT.PUT_LINE('Pretul nou este: ' || V_PRET_NOU);
    EXCEPTION 
        WHEN NO_DATA_FOUND THEN NULL;
    
END;
