CREATE OR REPLACE FUNCTION GET_VAL_COM_PROD(P_ID_PRODUS NUMBER) RETURN NUMBER IS
V_VAL NUMBER;
BEGIN
    SELECT 
    SUM(PRET*CANTITATE)
    INTO V_VAL
    FROM RAND_COMENZI
    WHERE ID_PRODUS=P_ID_PRODUS;
    
    RETURN NVL(V_VAL,0);
END;
/

