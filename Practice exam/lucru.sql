DECLARE 
    TYPE T_ANG IS TABLE OF VARCHAR2(100) INDEX BY PLS_INTEGER;
    V T_ANG;
    I PLS_INTEGER;
BEGIN
    SELECT NUME
    BULK COLLECT INTO V
    FROM ANGAJATI
    WHERE ID_FUNCTIE='SA_REP'
    AND SALARIUL BETWEEN 5000 AND 9000
    ORDER BY SALARIUL DESC;
    
    DBMS_OUTPUT.PUT_LINE(V.COUNT);
    DBMS_OUTPUT.PUT_LINE(V.FIRST);
    DBMS_OUTPUT.PUT_LINE(V.LAST);
    
    FOR I IN 1..V.COUNT LOOP
        DBMS_OUTPUT.PUT_LINE(V(I));
    END LOOP;
    
    
    I:=V.FIRST;
    WHILE I IS NOT NULL LOOP
        DBMS_OUTPUT.PUT_LINE(V(I));
        I:=V.NEXT(I);
    END LOOP;
END;
/

