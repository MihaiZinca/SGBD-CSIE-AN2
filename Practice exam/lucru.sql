DECLARE
    CURSOR C IS SELECT
    P.CATEGORIE,
    SUM(R.PRET*R.CANTITATE) AS VAL_T
    FROM PRODUSE P
    JOIN RAND_COMENZI R ON P.ID_PRODUS=R.ID_PRODUS
    GROUP BY P.CATEGORIE
    HAVING SUM(R.PRET*R.CANTITATE)>50000;
    
    CURSOR D(P_CATEG VARCHAR2) IS SELECT
        P.DENUMIRE_PRODUS,
        CATEGORIE,
        SUM(R.CANTITATE*R.PRET) AS VAL_T
        FROM PRODUSE P
        JOIN RAND_COMENZI R ON P.ID_PRODUS=R.ID_PRODUS
        WHERE P.CATEGORIE=P_CATEG
        GROUP BY P.DENUMIRE_PRODUS,CATEGORIE;
        
BEGIN
    FOR R IN C LOOP
        DBMS_OUTPUT.PUT_LINE(R.CATEGORIE);
        FOR S IN D(R.CATEGORIE) LOOP
            DBMS_OUTPUT.PUT_LINE(S.DENUMIRE_PRODUS||':'||S.VAL_T);
        END LOOP;
    END LOOP;

END;
/



