DECLARE
    TYPE R_PR IS RECORD(
    DENUMIRE_PRODUS VARCHAR2(50),
    VALOARE_TOTALA NUMBER,
    DATA_ULTIMA TIMESTAMP);
    
    TYPE T_PR IS TABLE OF R_PR INDEX BY PLS_INTEGER;
    V T_PR;
    I PLS_INTEGER;
BEGIN
    SELECT P.DENUMIRE_PRODUS,
        SUM(R.CANTITATE * R.PRET) AS VALOARE_TOTALA,
        MAX(C.DATA) AS DATA_ULTIMA
        BULK COLLECT INTO V
        FROM PRODUSE P
        JOIN RAND_COMENZI R ON P.ID_PRODUS=R.ID_PRODUS
        JOIN COMENZI C ON R.ID_COMANDA=C.ID_COMANDA
        GROUP BY P.DENUMIRE_PRODUS
        ORDER BY MAX(C.DATA) DESC;
        
        I:=V.FIRST;
        WHILE I IS NOT NULL LOOP
         DBMS_OUTPUT.PUT_LINE(V(I).denumire_produs || ' || Total=' || V(I).valoare_totala ||  ' || Ultima comanda=' || V(I).data_ultima);
            I:=V.NEXT(I);
        END LOOP;
        
END;
