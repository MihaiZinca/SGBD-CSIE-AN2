CREATE OR REPLACE PACKAGE PK IS
    FUNCTION TOTAL_VANZARI(P_ID_PRODUS NUMBER,P_AN NUMBER) RETURN NUMBER;
    PROCEDURE AFISARE_TOTAL(P_AN NUMBER);
    VAL_MICA EXCEPTION;
    PRAGMA EXCEPTION_INIT(VAL_MICA,-20000);
END;
/

CREATE OR REPLACE PACKAGE BODY PK IS
    FUNCTION TOTAL_VANZARI(P_ID_PRODUS NUMBER,P_AN NUMBER)RETURN NUMBER IS
    V_VAL NUMBER;
    BEGIN
        SELECT SUM(PRET*CANTITATE) INTO V_VAL
        FROM COMENZI C
        JOIN RAND_COMENZI R ON C.ID_COMANDA=R.ID_COMANDA
        WHERE EXTRACT(YEAR FROM DATA)=P_AN AND R.ID_PRODUS=P_ID_PRODUS;
        
        RETURN NVL(V_VAL,0);
    END;
    
    PROCEDURE AFISARE_TOTAL(P_AN NUMBER) IS
        CURSOR C IS SELECT
            ID_PRODUS,
            DENUMIRE_PRODUS,
            TOTAL_VANZARI(ID_PRODUS,P_AN) VAL
            FROM PRODUSE
            ORDER BY VAL DESC;
        R C%ROWTYPE;
        V_SUMA NUMBER DEFAULT 0;
        BEGIN
            OPEN C;
            LOOP
                FETCH C INTO R;
                EXIT WHEN C%NOTFOUND;
                DBMS_OUTPUT.PUT_LINE(R.ID_PRODUS||' '||R.DENUMIRE_PRODUS||' '||R.VAL);
                V_SUMA:=V_SUMA+R.VAL;
            END LOOP;
            CLOSE C;
            
            IF  V_SUMA<7000000 THEN
                RAISE_APPLICATION_ERROR(-20000,'MAI MICA');
            END IF;
        END;
        
END;
/

BEGIN
    PK.AFISARE_TOTAL(2020);
    EXCEPTION
        WHEN PK.VAL_MICA THEN
            DBMS_OUTPUT.PUT_LINE('A APARUT EROAREA'||SQLERRM);
END;
/



