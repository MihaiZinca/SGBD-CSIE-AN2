CREATE OR REPLACE PACKAGE PKE IS
    FUNCTION TOTAL_COM(P_ID_CLIENT NUMBER, P_AN NUMBER) RETURN NUMBER;
END;
/

CREATE OR REPLACE PACKAGE BODY PKE IS

    FUNCTION TOTAL_COM(P_ID_CLIENT NUMBER, P_AN NUMBER) RETURN NUMBER IS
    V_VAL NUMBER;
    BEGIN
        SELECT SUM(R.PRET*R.CANTITATE)INTO V_VAL
        FROM COMENZI C
        JOIN RAND_COMENZI R ON C.ID_COMANDA=R.ID_COMANDA
        WHERE EXTRACT(YEAR FROM DATA)=P_AN AND C.ID_CLIENT=P_ID_CLIENT;
        
        RETURN NVL(V_VAL,0);
    END;

END;
/

DECLARE
    TYPE R_ANG IS RECORD(
    id_client number,
    prenume_client varchar2(50),
    nume_client varchar2(50),
    total number);
    
    TYPE T_ANG IS TABLE OF R_ANG INDEX BY PLS_INTEGER;
    V T_ANG;
    I PLS_INTEGER;
BEGIN
    SELECT ID_CLIENT,
    PRENUME_CLIENT,
    NUME_CLIENT,
    PKE.TOTAL_COM(ID_CLIENT,2024) 
    BULK COLLECT INTO V
    FROM CLIENTI
    WHERE nivel_venituri = 'F: 110,000 - 129,999'
    ORDER BY ID_CLIENT ASC;
    
    DBMS_OUTPUT.PUT_LINE('Clienti cu nivelul de venituri F: 110,000 - 129,999 pentru anul 2024:');
    
    I:=V.FIRST;
    WHILE I IS NOT NULL LOOP
        DBMS_OUTPUT.PUT_LINE('Clientul:'||V(I).id_client||'-'||V(I).nume_client||' '||V(I).prenume_client||' , total comenzi:'||V(I).total);
        I:=V.NEXT(I);
    END LOOP;
END;
/
    

