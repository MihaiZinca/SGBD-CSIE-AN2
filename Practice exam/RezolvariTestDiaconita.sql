CREATE OR REPLACE PACKAGE PACK IS
    FUNCTION OBTINE_TOTAL(P_ID_DEPARTAMENT NUMBER,P_AN NUMBER)RETURN NUMBER;
END;
/

CREATE OR REPLACE PACKAGE BODY PACK IS
    
    FUNCTION OBTINE_TOTAL(P_ID_DEPARTAMENT NUMBER,P_AN NUMBER)RETURN NUMBER IS
        V_VAL NUMBER;
    BEGIN
        SELECT 
            SUM(SALARIUL) INTO V_VAL
            FROM ANGAJATI A
            WHERE ID_DEPARTAMENT=P_ID_DEPARTAMENT 
            AND EXTRACT(YEAR FROM DATA_ANGAJARE)=P_AN;
            
        RETURN NVL(V_VAL,0);
    END;
    
END;
/

DECLARE
    TYPE R_SAL IS RECORD(
    ID_DEPARTAMENT NUMBER,
    DENUMIRE_DEPARTAMENT VARCHAR2(30),
    ORAS VARCHAR2(20),
    TOTAL NUMBER);
    
    TYPE T_SAL IS TABLE OF R_SAL INDEX BY PLS_INTEGER;
    V T_SAL;
    I PLS_INTEGER;
BEGIN
    SELECT 
    D.ID_DEPARTAMENT,
    D.DENUMIRE_DEPARTAMENT,
    L.ORAS,
    PACK.OBTINE_TOTAL(D.ID_DEPARTAMENT,2023)
    BULK COLLECT INTO V
    FROM DEPARTAMENTE D
    JOIN LOCATII L ON D.ID_LOCATIE=L.ID_LOCATIE
    WHERE L.ID_TARA='US'
    ORDER BY D.ID_DEPARTAMENT ASC;
    
    I:=V.FIRST;
    WHILE I IS NOT NULL LOOP
        DBMS_OUTPUT.PUT_LINE('Departament '||V(I).ID_DEPARTAMENT||'-'||V(I).DENUMIRE_DEPARTAMENT||'oras:'||V(I).ORAS||'total sal:'||V(I).total);
        I:=V.NEXT(I);
    END LOOP;
    
END;
/


