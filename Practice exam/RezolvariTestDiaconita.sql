CREATE OR REPLACE PROCEDURE ACTUALIZEAZA_LIMITA_CREDIT(P_ID_CLIENT NUMBER,P_PROCENT NUMBER) IS
    CURSOR C IS SELECT
        ID_CLIENT,
        LIMITA_CREDIT
        FROM CLIENTI
        WHERE ID_CLIENT=P_ID_CLIENT;
        
    R C%ROWTYPE;
    V_NR NUMBER DEFAULT 0;
BEGIN
    OPEN C;
    LOOP
        FETCH C INTO R;
        EXIT WHEN C%NOTFOUND;
        
        V_NR:=V_NR+1;
        DBMS_OUTPUT.PUT_LINE('CLIENT ACTUALIZAZT:'||R.ID_CLIENT);
        DBMS_OUTPUT.PUT_LINE('LIMITA CREDIT INITIALA:'||R.LIMITA_CREDIT);
        DBMS_OUTPUT.PUT_LINE('LIMITA CREDIT FINALA:'||(R.LIMITA_CREDIT *(1+P_PROCENT/100)));
        
        UPDATE CLIENTI
        SET LIMITA_CREDIT=R.LIMITA_CREDIT *(1+P_PROCENT/100)
        WHERE ID_CLIENT=R.ID_CLIENT;
    END LOOP;
    CLOSE C;
    
    IF V_NR=0 THEN
        RAISE_APPLICATION_ERROR(-20000,'NU EXISTA CLIENTUL CU ID UL ACESTA');
    END IF;
        
END;
/

DECLARE
    NU_EXI EXCEPTION;
    PRAGMA EXCEPTION_INIT(NU_EXI,-20000);
BEGIN
    ACTUALIZEAZA_LIMITA_CREDIT(101,20);
    
    EXCEPTION
        WHEN NU_EXI THEN
            DBMS_OUTPUT.PUT_LINE('A APARUT EROAREA '||SQLERRM);

END;
