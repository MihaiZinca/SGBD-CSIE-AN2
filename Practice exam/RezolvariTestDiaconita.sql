CREATE OR REPLACE PROCEDURE ACTUALIZEAZA_PRET_PRODUS(P_ID_PRODUS NUMBER,P_PROCENT NUMBER) IS
    CURSOR C IS SELECT
    P.ID_PRODUS,
    P.PRET_LISTA,
    P.PRET_MIN 
    FROM PRODUSE P
    WHERE P.ID_PRODUS=P_ID_PRODUS;
    
    R C%ROWTYPE;
    V_GASIT NUMBER DEFAULT 0;
    
    BEGIN
        OPEN C;
        LOOP
            FETCH C INTO R;
            EXIT WHEN C%NOTFOUND;
            
            V_GASIT:=V_GASIT+1;
            -- Afisam valorile initiale
         DBMS_OUTPUT.PUT_LINE('Produs actualizat: ' || R.ID_PRODUS);
         DBMS_OUTPUT.PUT_LINE('Pret lista initial: ' || R.PRET_LISTA || ', pret lista final: ' || (R.PRET_LISTA * (1 + P_PROCENT/100)));
         DBMS_OUTPUT.PUT_LINE('Pret minim initial: ' || R.PRET_MIN || ', pret minim final: ' || (R.PRET_MIN * (1 + P_PROCENT/100)));
            
            UPDATE PRODUSE 
            SET 
            PRET_LISTA = PRET_LISTA * (1 + P_PROCENT/100),
            PRET_MIN = PRET_MIN * (1 + P_PROCENT/100)
            WHERE ID_PRODUS = R.ID_PRODUS;
        END LOOP;
        CLOSE C;
        
        IF V_GASIT=0 THEN
            RAISE_APPLICATION_ERROR(-20000,'NU EXISTA');
        END IF;
    
    
    END;
    /


DECLARE
    E_EXC EXCEPTION;
    PRAGMA EXCEPTION_INIT(E_EXC, -20000);
BEGIN
    ACTUALIZEAZA_PRET_PRODUS(1733, 10);
EXCEPTION
    WHEN E_EXC THEN
        DBMS_OUTPUT.PUT_LINE(SQLERRM);
END;
/

